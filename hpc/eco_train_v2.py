# --------------------------------------------------------------- two-phase setup
# Phase boundary: steps for Phase 1 vs Phase 2
nudge_start = int(TARGET_TOTAL * (1.0 - NUDGE_FRAC))

class TwoPhaseCallback(TrainerCallback):
    """Switch hyperparameters at the phase boundary.
    Phase 1: high LR, no gradient clipping
    Phase 2: low LR (nudge), gradient clipping ON, cosine schedule
    """
    def __init__(self, nudge_start, nudge_lr, phase1_lr, step_offset=0):
        self.nudge_start = nudge_start
        self.nudge_lr = nudge_lr
        self.phase1_lr = phase1_lr
        self.step_offset = step_offset
        self.switched = False

    def on_step_begin(self, args, state, control, **kw):
        real_step = state.global_step + self.step_offset
        if not self.switched and real_step >= self.nudge_start:
            self.switched = True
            # Switch to nudge LR
            optimizer = kw.get("optimizer")
            if optimizer is not None:
                for pg in optimizer.param_groups:
                    pg["lr"] = self.nudge_lr
            # Re-enable gradient clipping
            args.max_grad_norm = 1.0
            if IS_MAIN:
                print(f"\n{'='*60}", flush=True)
                print(f"PHASE 2 NUDGE START at step {state.global_step}", flush=True)
                print(f"  lr: {self.phase1_lr} -> {self.nudge_lr}", flush=True)
                print(f"  max_grad_norm: 1e9 -> 1.0", flush=True)
                print(f"{'='*60}\n", flush=True)
        return control

