# --------------------------------------------------------- staged freeze callback
from transformers import TrainerCallback

class ExpertFreezeCallback(TrainerCallback):
    def __init__(self, params, freeze_until):
        self.params = params
        self.freeze_until = freeze_until
    def on_pre_optimizer_step(self, args, state, control, **kw):
        if state.global_step < self.freeze_until:
            for p in self.params:
                if p.grad is not None:
                    p.grad.zero_()
        return control

class MoEGradTieCallback(TrainerCallback):
    """Apply gradient-sum tying before each optimizer step (3rd place)."""
    def __init__(self, tie_fn):
        self.tie_fn = tie_fn
    def on_pre_optimizer_step(self, args, state, control, **kw):
        self.tie_fn()
        return control

